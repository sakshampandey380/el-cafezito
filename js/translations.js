// Helper to detect browser language
function detectBrowserLanguage() {
  try {
    const rawLang = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    const prefix = rawLang.toLowerCase().slice(0, 2);
    const match = SUPPORTED_LANGUAGES.find(l => l.code === prefix);
    return match ? match.code : 'en';
  } catch (e) {
    return 'en';
  }
}

// Get the actual active language code
function getActiveLanguage() {
  try {
    const saved = localStorage.getItem('el_cafezito_lang');
    if (!saved || saved === 'auto') {
      return detectBrowserLanguage();
    }
    return saved;
  } catch (e) {
    return 'en';
  }
}

function getSavedLanguagePreference() {
  try {
    return localStorage.getItem('el_cafezito_lang') || 'auto';
  } catch (e) {
    return 'auto';
  }
}

function getTranslation(key, lang) {
  const targetLang = lang || getActiveLanguage();
  const dict = TRANSLATIONS[targetLang] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}

